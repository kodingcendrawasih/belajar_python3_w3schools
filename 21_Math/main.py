# 🔰🔰 MATH (MATEMATIKA)

# ⚡ Fungsi Matematika Bawaan Python

# 🔖 min()
min_value = min(5, 10, 2, 8)
print('Nilai minimum:', min_value)

# 🔖 max()
max_value = max(5, 10, 2, 8)
print('Nilai maximum:', max_value)

# 🔖 abs()
absolute_value = abs(-7)
print('Nilai absolut:', absolute_value)

# 🔖 pow()
power_value = pow(2, 3)
print('Nilai pangkat:', power_value)

# ⚡ Model Matematika Bawaan Python

import math

# 🔖 math.ceil()
ceil_value = math.ceil(4.2)
print('Nilai ceil:', ceil_value)

# 🔖 math.floor()
floor_value = math.floor(4.8)
print('Nilai floor:', floor_value)

# 🔖 math.sqrt()
sqrt_value = math.sqrt(16)
print('Nilai akar kuadrat:', sqrt_value)

# 🔖 math.pi()
pi_value = math.pi
print('Nilai pi:', pi_value)
print('Nilai pi:', round(pi_value, 2))  # Membulatkan nilai pi hingga 2 desimal


