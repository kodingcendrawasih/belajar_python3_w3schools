# 🔰🔰 Operator Aritmatika 
'''
operator ini digunakan dengan nilai numerik untuk 
melakukan operasi matematika umum
'''

# Addition (Penjumlahan)
print(1 + 2) # 3
# Subtraction (Pengurangan)
print(2 - 1) # 1
# Multiplication (Perkalian)
print(2 * 3) # 6
# Division (Pembagian) -> hasilnya selalu float
print(4 / 2) # 2.0
# Modulus (Sisa Bagi)
print(5 % 2) # 1
# Exponentiation (Pangkat)
print(5 ** 2) # 25
# Floor Division (Pembagian Dan Membulatkan Hasil Ke Bawah)
print(4 // 2) # 2.0 -> dibulatkan ke bawah -> 2


