# 🔰🔰 OPERATOR PERBANDINGAN
'''
operator ini digunakan untuk membandingkan
dua buah nilai. dan hasilnya akan selalu boolean
'''

print(2 > 2) # false
print(2 < 2) # false
print(2 >= 2) # True
print(2 <= 2) # True
print(2 == 2) # True
print(2 != 2) # False

# ⚡ Penggabungan Operator Perbandingan
#- di python kitong bisa menggabungkan operator perbandingan

print(2 < 5 < 1) # False
print(5 > 2 > 3) # True
print(5 > 2 < 1) # False

print(1 < 3 and 1 > 3) # False
print(1 < 3 or 1 > 3) # True

