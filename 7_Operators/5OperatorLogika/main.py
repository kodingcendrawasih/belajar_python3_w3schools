# 🔰🔰 OPERATOR LOGIKA
'''
Operator logika digunakan untuk menggabungkan pernytaan
bersyarat
'''

# ⚡ and
print(1 > 2 and 1 < 2) # False -> harus keduanya benilai True

# ⚡ or
print(1 > 2 or 1 < 2) # True -> karena salah satu kondisi bernilai True

# ⚡ not
print(not(1 < 2 and 1 > 0)) # False -> kebalikan dari True

